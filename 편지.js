// ENTER BUTTON
// =========================

enterBtn.addEventListener("click", () => {

    landing.classList.add("hidden");

    lettersPage.classList.remove("hidden");

});

// =========================
// CREATE LETTER CARDS
// =========================

letters.forEach((letter, index) => {

    const card = document.createElement("div");

    card.classList.add("date-card");

    const unlocked = index <= unlockedCount;

    card.innerHTML = `
        <span>${letter.display}</span>
        <span>${unlocked ? "🤍" : "🔒"}</span>
    `;

    if (!unlocked) {

        card.classList.add("locked");

        card.addEventListener("click", () => {

            showToast("Not Unlocked");

        });

    } else {

        card.addEventListener("click", () => {

            openLetter(letter);

        });

    }

    lettersContainer.appendChild(card);

});

// =========================
// OPEN LETTER
// =========================

function openLetter(letter) {

    letterTitle.textContent = letter.title;

    letterText.textContent = letter.text;

    audioPlayer.src = letter.audio;

    modal.classList.remove("hidden");

}

// =========================
// CLOSE LETTER
// =========================

closeBtn.addEventListener("click", () => {

    modal.classList.add("hidden");

    audioPlayer.pause();

});

// =========================
// TOAST
// =========================

function showToast(message) {

    toast.textContent = message;

    toast.classList.add("show");

    setTimeout(() => {

        toast.classList.remove("show");

    }, 2500);

}